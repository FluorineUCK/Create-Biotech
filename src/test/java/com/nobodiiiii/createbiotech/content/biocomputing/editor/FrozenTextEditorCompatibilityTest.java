package com.nobodiiiii.createbiotech.content.biocomputing.editor;

import static org.junit.jupiter.api.Assertions.*;

import com.nobodiiiii.createbiotech.content.biocomputing.computation.DataValue;
import com.nobodiiiii.createbiotech.content.biocomputing.computer.flow.FlowProgram;
import com.nobodiiiii.createbiotech.content.biocomputing.computer.flow.FlowRuntime;
import com.nobodiiiii.createbiotech.content.biocomputing.persistence.ArchiveException;
import com.nobodiiiii.createbiotech.content.biocomputing.persistence.ArchiveLimits;
import com.nobodiiiii.createbiotech.content.biocomputing.persistence.FlowBlockNbtCodec;
import com.nobodiiiii.createbiotech.content.biocomputing.persistence.ValueNbtCodec;
import java.util.LinkedHashMap;
import java.util.Set;
import net.minecraft.nbt.NbtAccounter;
import net.minecraft.nbt.NbtIo;
import org.junit.jupiter.api.Test;

class FrozenTextEditorCompatibilityTest {
    // These are the original payloads from native frame 2396, not generated by either codec under test.
    @Test void aTimedExtensionArchivePreservesItsEditableArgumentsAndTheInstalledImage() throws Exception {
        var limits = new ArchiveLimits(10000, 100000, 1000000);
        var original = NbtIo.readCompressed(getClass().getResourceAsStream("/old-text-editor-player.nbt"),
            NbtAccounter.create(16 * 1024 * 1024));
        var active = original.getCompound("BiocomputingEditor").getCompound("Active");
        var owner = FlowBlockNbtCodec.decode(original.getCompound("Biocomputing"), limits);
        assertEquals(FlowRuntime.Status.COMPLETE, owner.state().status());
        assertEquals(5934, owner.state().work());
        var raw = assertInstanceOf(DataValue.RecordValue.class, ValueNbtCodec.decode(active, limits));
        assertEquals(new DataValue.IntegerValue(51), raw.field("version"));

        var document = ProgramDocumentCodec.decode(raw);
        var flow = document.flow().orElseThrow();
        assertEquals(Set.of("block_1", "block_2"), flow.inline().keySet(), "Do not fall back to a graph without operand edit metadata");
        assertEquals(Set.of("x", "y", "z", "device", "session", "revision", "line"), flow.inline().get("block_1").outputs().keySet());
        assertEquals(Set.of("value"), flow.inline().get("block_2").outputs().keySet());
        assertTrue(flow.steps().stream().anyMatch(step -> step instanceof FlowProgram.Sleep wait && wait.sourceId().equals("block_2") && wait.displayedUnit() == FlowProgram.WaitUnit.SECONDS));
        assertEquals(owner.program(), flow.program(document.archive()));
        assertEquals(owner.initialInputs(), flow.initial());
        assertDoesNotThrow(document::validateTerminalTargets);
        var written = ProgramDocumentCodec.encode(document);
        assertEquals(new DataValue.IntegerValue(56), written.field("version"), "A deliberate new write still uses the current schema");
        assertEquals(document, ProgramDocumentCodec.decode(written));
        for (int invalidVersion : new int[]{50, 52}) {
            var wrong = new LinkedHashMap<>(raw.fields());
            wrong.put("version", new DataValue.IntegerValue(invalidVersion));
            assertThrows(ArchiveException.class, () -> ProgramDocumentCodec.decode(new DataValue.RecordValue(wrong)));
        }
    }
}
