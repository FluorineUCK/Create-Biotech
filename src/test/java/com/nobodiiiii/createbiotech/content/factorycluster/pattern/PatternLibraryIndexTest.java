	@Test
	void literalHistoricalArchiveKeepsExactTagsAndNonHeadRequesterCursor() throws Exception {
		// Fixed historical schema fixture, never generated by the codec under test.
		var historical = net.minecraft.nbt.TagParser.parseTag("""
			{PageOrder:[],Cache:[],FingerprintCursor:0,Generation:7L,Complete:1b,
			 Queries:[{QueryId:[I;0,0,0,6],RequesterComputerId:[I;0,0,0,1],LogisticsId:[I;0,0,0,3],
			  RequestedOutput:{Stack:{id:"minecraft:paper",count:1}},Generation:7L,Cursor:0}],
			 Replies:[{QueryId:[I;0,0,0,4],RequesterComputerId:[I;0,0,0,1],LogisticsId:[I;0,0,0,3],Generation:7L,Status:"NOT_FOUND"},
			  {QueryId:[I;0,0,0,5],RequesterComputerId:[I;0,0,0,2],LogisticsId:[I;0,0,0,3],Generation:7L,Status:"NOT_FOUND"}],
			 ReplyRequesterCursor:[I;0,0,0,2]}
			""");
		var original = historical.copy();
		var loaded = ProductionLibraryIndexArchive.load(historical, REGISTRIES);
		assertFalse(loaded.hadCorruption());
		assertEquals(original, ProductionLibraryIndexArchive.save(loaded.state(), REGISTRIES));
		assertEquals(1, loaded.state().activeQueryCount());
		assertEquals(new UUID(0, 6), loaded.state().activeQueries().getFirst().queryId());
		assertTrue(loaded.state().drainReplies(new UUID(0, 1), 8).isEmpty());
		assertEquals(new UUID(0, 5), loaded.state().drainReplies(new UUID(0, 2), 8).getFirst().queryId());
		assertEquals(new UUID(0, 4), loaded.state().drainReplies(new UUID(0, 1), 8).getFirst().queryId());
		assertEquals(original, historical);
		assertFalse(ProductionLibraryIndexArchive.CODEC.hasPriorShape(historical));
		var prior = historical.copy(); prior.remove("ReplyRequesterCursor");
		assertTrue(ProductionLibraryIndexArchive.CODEC.hasPriorShape(prior));
		var old = ProductionLibraryIndexArchive.load(prior, REGISTRIES);
		assertFalse(old.hadCorruption());
		var upgraded = prior.copy(); upgraded.putUUID("ReplyRequesterCursor", new UUID(0, 1));
		assertEquals(upgraded, ProductionLibraryIndexArchive.save(old.state(), REGISTRIES));
	}

